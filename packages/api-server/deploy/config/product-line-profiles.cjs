function getProductLineProfile(line) {
  const profile = PROFILES[line]
  if (!profile) throw new Error(`Unknown product line profile: ${line}`)
  return profile
}

function productLineForApiApp(appRel) {
  const normalized = appRel.replace(/\\/g, '/')
  return Object.values(PROFILES).find((profile) => profile.api.appPath === normalized)?.id ?? null
}

function profileForApiApp(appRel) {
  const line = productLineForApiApp(appRel)
  return line ? getProductLineProfile(line) : null
}

