/**
 * Migrate lib + hooks + admin modules từ main/backend → packages/admin-app.
 *
 * Usage: node script-system/admin/migrate-admin-modules.cjs [--modules staff,tags]
 */
const fs = require("node:fs")
const path = require("node:path")
const { ROOT } = require("../lib/paths.cjs")
const { PRODUCT_LINES } = require("../lib/monorepo-apps.cjs")
const { rewritePackageImports } = require("./lib/rewrite-package-imports.cjs")
const {
  isAutoGeneratedModulePage,
} = require("./lib/admin-host-lib-rules.cjs")

const MAIN_BACKEND = path.join(ROOT, PRODUCT_LINES.main.backend.path)
const PACKAGE_ROOT = path.join(ROOT, "packages/admin-app")
const PACKAGE_SRC = path.join(PACKAGE_ROOT, "src")
const DEFAULT_MODULES = [
  "staff",
  "rbac",
  "categories",
  "tags",
  "guides",
  "posts",
  "cameras",
  "templates",
  "screens",
  "locations",
  "speakers",
  "settings",
  "file-storage",
  "data",
  "events",
  "departments",
  "academic-years",
  "courses",
  "majors",
  "training-levels",
  "training-systems",
  "products",
  "orders",
  "promo-codes",
  "seo-metas",
  "contact-requests",
  "parent-students",
  "my-students",
]

const args = process.argv.slice(2)
const modArg = args.find((a) => a.startsWith("--modules="))
const modulesOnly = Boolean(modArg)
const modules = modArg
  ? modArg.split("=")[1].split(",").map((s) => s.trim()).filter(Boolean)
  : DEFAULT_MODULES

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, acc)
    else if (/\.(ts|tsx)$/.test(entry.name)) acc.push(full)
  }
  return acc
}

function copyDir(src, dest) {
  if (!fs.existsSync(src)) {
    console.warn(`[migrate-admin] skip missing: ${src}`)
    return
  }
  fs.mkdirSync(dest, { recursive: true })
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, entry.name)
    const to = path.join(dest, entry.name)
    if (entry.isDirectory()) copyDir(from, to)
    else fs.copyFileSync(from, to)
  }
}

function rewriteTree(dir) {
  for (const file of walk(dir)) {
    const raw = fs.readFileSync(file, "utf8")
    const next = rewritePackageImports(raw)
    if (next !== raw) fs.writeFileSync(file, next)
  }
}

function migrateLib() {
  const destLib = path.join(PACKAGE_SRC, "lib")
  const stubSrc = path.join(
    ROOT,
    "apps/hub-event/hub-event-checkin-frontend/src/lib/admin/product-image-storage-stub.ts",
  )
  if (fs.existsSync(stubSrc)) {
    fs.copyFileSync(
      stubSrc,
      path.join(destLib, "product-image-storage-stub.ts"),
    )
  }
  rewriteTree(destLib)
  console.log(
    "[migrate-admin] lib: giữ package làm nguồn — chỉ sync stub check-in + rewrite import",
  )
}

function migrateHooks() {
  const destHooks = path.join(PACKAGE_SRC, "hooks")
  rewriteTree(destHooks)
  console.log(
    "[migrate-admin] hooks: giữ package làm nguồn — chỉ rewrite import trong package",
  )
}

function migrateTypes() {
  const srcTypes = path.join(MAIN_BACKEND, "src/types")
  const destTypes = path.join(PACKAGE_SRC, "types")
  if (!fs.existsSync(srcTypes)) return
  fs.mkdirSync(destTypes, { recursive: true })
  for (const entry of fs.readdirSync(srcTypes, { withFileTypes: true })) {
    if (!entry.isFile() || !/\.ts$/.test(entry.name)) continue
    const destFile = path.join(destTypes, entry.name)
    if (fs.existsSync(destFile)) {
      console.log(
        `[migrate-admin] skip type ${entry.name} (đã có trong package)`,
      )
      continue
    }
    fs.copyFileSync(path.join(srcTypes, entry.name), destFile)
  }
  rewriteTree(destTypes)
  console.log("[migrate-admin] types → packages/admin-app/src/types")
}

function isGeneratedOnlyAppModule(mod) {
  const pagePath = path.join(MAIN_BACKEND, "src/app", mod, "page.tsx")
  if (!fs.existsSync(pagePath)) return false
  const componentDir = path.join(MAIN_BACKEND, "src/app", mod, "_component")
  if (fs.existsSync(componentDir)) return false
  const content = fs.readFileSync(pagePath, "utf8")
  return isAutoGeneratedModulePage(content)
}

function migrateModules() {
  for (const mod of modules) {
    if (isGeneratedOnlyAppModule(mod)) {
      console.log(
        `[migrate-admin] skip module ${mod} (app chỉ còn AUTO-GENERATED — sửa trong package)`,
      )
      continue
    }
    const src = path.join(MAIN_BACKEND, "src/app", mod)
    const dest = path.join(PACKAGE_SRC, "modules", mod)
    if (!fs.existsSync(src)) {
      console.warn(`[migrate-admin] skip missing app module: ${mod}`)
      continue
    }
    if (fs.existsSync(dest)) {
      fs.rmSync(dest, { recursive: true, force: true })
    }
    copyDir(src, dest)
    rewriteTree(dest)
    console.log(`[migrate-admin] module ${mod} (legacy copy từ app)`)
  }
}

function patchRuntimeNavigationImport() {
  const nav = path.join(PACKAGE_SRC, "runtime/use-admin-module-navigation.ts")
  if (!fs.existsSync(nav)) return
  let content = fs.readFileSync(nav, "utf8")
  if (!content.includes('useAdminModuleNavigation')) return
  for (const file of walk(path.join(PACKAGE_SRC, "modules"))) {
    let raw = fs.readFileSync(file, "utf8")
    if (!raw.includes("useAdminCrudNavigation")) continue
    if (raw.includes("useAdminModuleNavigation")) continue
    if (!raw.includes('from "@workspace/admin-app/lib/admin-navigation"')) {
      raw = raw.replace(
        /from ["']@workspace\/admin-app\/lib\/admin-navigation["']/g,
        'from "@workspace/admin-app/runtime"',
      )
    }
    raw = rewritePackageImports(raw)
    if (!/useAdminModuleNavigation/.test(raw) && /useAdminCrudNavigation/.test(raw)) {
      raw = `import { useAdminModuleNavigation } from "@workspace/admin-app/runtime"\n${raw}`
    }
    fs.writeFileSync(file, raw)
  }
}

function addNavigationImportToModules() {
  for (const file of walk(path.join(PACKAGE_SRC, "modules"))) {
    let content = fs.readFileSync(file, "utf8")
    if (!content.includes("useAdminModuleNavigation(")) continue
    if (content.includes('from "@workspace/admin-app/runtime"')) {
      if (!content.includes("useAdminModuleNavigation")) {
        content = content.replace(
          /import\s+\{([^}]+)\}\s+from\s+["']@workspace\/admin-app\/runtime["']/,
          (line, specs) => {
            if (/\buseAdminModuleNavigation\b/.test(specs)) return line
            return `import {${specs.trim()}, useAdminModuleNavigation } from "@workspace/admin-app/runtime"`
          },
        )
        fs.writeFileSync(file, content)
      }
      continue
    }
    content = `import { useAdminModuleNavigation } from "@workspace/admin-app/runtime"\n${content}`
    fs.writeFileSync(file, content)
  }
}

if (!modulesOnly) {
  migrateLib()
  migrateHooks()
  migrateTypes()
}
migrateModules()
patchRuntimeNavigationImport()
addNavigationImportToModules()
console.log(`[migrate-admin] done — ${modules.length} modules`)
