/**
 * Quy tắc lib/hooks trên app host admin — package là nguồn sự thật.
 * App chỉ giữ implementation local (SDK, auth route) hoặc re-export mỏng.
 */
const fs = require("node:fs")
const path = require("node:path")

const PACKAGE_STAR_REEXPORT_RE =
  /^export\s+\*\s+from\s+["']@workspace\/admin-app\/(?:lib|hooks|features)\/[^"']+["']\s*;?\s*$/

const PACKAGE_NAMED_REEXPORT_RE =
  /^export\s+(?:type\s+)?\{[\s\S]*\}\s+from\s+["']@workspace\/admin-app\/(?:lib|hooks|features)\/[^"']+["']\s*;?\s*$/

function stripLeadingUseClient(content) {
  return content.replace(/^["']use client["']\s*\r?\n?/, "").trim()
}

/** @param {string} body */
function isPackageReexportBody(body) {
  if (!body) return false
  if (PACKAGE_STAR_REEXPORT_RE.test(body)) return true
  if (PACKAGE_NAMED_REEXPORT_RE.test(body)) return true
  return false
}

/** @param {string} content */
function isThinPackageReexport(content) {
  const body = stripLeadingUseClient(content).trim()
  return isPackageReexportBody(body)
}

/** @param {string} content */
function isThinUiReexport(content) {
  const body = stripLeadingUseClient(content).trim()
  if (!body.includes("@ui/")) return false
  if (/\b(function|=>|useEffect|useState|useRef)\b/.test(body)) return false
  if (/^import\s+(?!type\b)/m.test(body)) return false
  return /from\s+["']@ui\//.test(body) && /^export\s+/m.test(body)
}

/** @param {string} content */
function isAutoGeneratedModulePage(content) {
  return (
    content.includes("AUTO-GENERATED") &&
    /export\s+\{\s*default\s*\}\s+from\s+["']@workspace\/admin-app\/modules\//.test(
      content,
    )
  )
}

function walkTs(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walkTs(full, acc)
    else if (/\.(ts|tsx)$/.test(entry.name)) acc.push(full)
  }
  return acc
}

/**
 * @param {string[]} errors
 * @param {{
 *   libDir: string,
 *   pathPrefix: string,
 *   substantiveBasenames: Set<string>,
 *   allowUiReexport?: boolean,
 * }} opts
 */
function verifyAdminHostLibDir(errors, opts) {
  const { libDir, pathPrefix, substantiveBasenames, allowUiReexport = false } =
    opts
  if (!fs.existsSync(libDir)) {
    errors.push(`thiếu thư mục lib host: ${pathPrefix}`)
    return
  }

  for (const file of walkTs(libDir)) {
    const rel = path.relative(libDir, file).replace(/\\/g, "/")
    const display = `${pathPrefix}${rel}`
    const base = path.basename(file)
    const content = fs.readFileSync(file, "utf8")

    if (substantiveBasenames.has(base) || substantiveBasenames.has(rel)) {
      if (isThinPackageReexport(content)) {
        errors.push(
          `${display}: file substantive không được là re-export package`,
        )
      }
      continue
    }

    if (isThinPackageReexport(content)) continue
    if (allowUiReexport && isThinUiReexport(content)) continue

    const lines = stripLeadingUseClient(content).split(/\r?\n/).length
    errors.push(
      `${display}: lib host phải re-export @workspace/admin-app (đang ${lines} dòng — duplicate?)`,
    )
  }
}

/**
 * @param {string[]} errors
 * @param {{
 *   hooksDir: string,
 *   pathPrefix: string,
 *   substantiveBasenames: Set<string>,
 * }} opts
 */
function verifyAdminHostHooksDir(errors, opts) {
  const { hooksDir, pathPrefix, substantiveBasenames } = opts
  if (!fs.existsSync(hooksDir)) return

  for (const file of walkTs(hooksDir)) {
    const rel = path.relative(hooksDir, file).replace(/\\/g, "/")
    const display = `${pathPrefix}${rel}`
    const base = path.basename(file)
    const content = fs.readFileSync(file, "utf8")

    if (substantiveBasenames.has(base) || substantiveBasenames.has(rel)) {
      if (isThinPackageReexport(content) && !isThinUiReexport(content)) {
        // substantive hook — ok if fat
      } else if (isThinPackageReexport(content)) {
        errors.push(`${display}: hook substantive không được re-export`)
      }
      continue
    }

    if (isThinPackageReexport(content)) continue
    if (isThinUiReexport(content)) continue

    const lines = stripLeadingUseClient(content).split(/\r?\n/).length
    if (lines > 30) {
      errors.push(
        `${display}: hook host nên re-export package/@ui (đang ${lines} dòng)`,
      )
    }
  }
}

module.exports = {
  isThinPackageReexport,
  isThinUiReexport,
  isAutoGeneratedModulePage,
  verifyAdminHostLibDir,
  verifyAdminHostHooksDir,
  MAIN_LIB_SUBSTANTIVE: new Set(["api.ts"]),
  CHECKIN_LIB_ADMIN_SUBSTANTIVE: new Set([
    "api.ts",
    "auth-routes.ts",
    "cameras-query.ts",
    "product-image-storage-stub.ts",
  ]),
  STORE_LIB_ADMIN_SUBSTANTIVE: new Set([
    "api.ts",
    "auth-routes.ts",
    "product-image-storage-stub.ts",
  ]),
}
